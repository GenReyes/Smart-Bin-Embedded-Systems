#!/usr/bin/env python3
"""Packs Web Dashboard/smartbin-dashboard.html into firmware/SmartBin/dashboard_gz.h
so each bin serves the dashboard at http://<bin-ip>/ . Run it again after changing the
dashboard, then upload the firmware.

    python firmware/tools/embed_dashboard.py
"""
import gzip
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = root / "Web Dashboard" / "smartbin-dashboard.html"
dst = root / "firmware" / "SmartBin" / "dashboard_gz.h"

data = gzip.compress(src.read_bytes(), compresslevel=9, mtime=0)
rows = [", ".join("0x%02x" % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
dst.write_text(
    "#pragma once\n// Generated by firmware/tools/embed_dashboard.py from Web Dashboard/smartbin-dashboard.html. Do not edit.\n"
    "#include <Arduino.h>\n"
    "const size_t DASHBOARD_GZ_LEN = %d;\n"
    "const uint8_t DASHBOARD_GZ[] PROGMEM = {\n  %s\n};\n" % (len(data), ",\n  ".join(rows)),
    encoding="ascii",
)
print("%s: %d bytes of HTML -> %d bytes gzipped" % (dst.name, src.stat().st_size, len(data)))
